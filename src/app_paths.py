# -*- coding: utf-8 -*-
"""
app_paths.py - определение реальных путей программы, единообразно работающее и при запуске из исходников (python -m src.main), и внутри
собранной PyInstaller-программы (--onedir и --onefile).

ПОЧЕМУ ЭТО ОТДЕЛЬНЫЙ МОДУЛЬ, А НЕ os.path.dirname(__file__) НАПРЯМУЮ: обычный подход "путь относительно __file__" ломается внутри собранной
программы - PyInstaller распаковывает/копирует код в служебную структуру (временную папку при каждом запуске для --onefile, либо
внутреннюю папку _internal рядом с exe для --onedir), и __file__ там указывает на эту служебную папку, а не на реальное расположение
exe-файла, которое видит пользователь. Использовать __file__ напрямую для путей к пользовательским данным (база, резервные копии, пароль) -
означает, что при сборке эти данные окажутся не рядом с программой, а где-то во временной/служебной папке, и в режиме --onefile могут даже
теряться между запусками.

Два принципиально разных вида путей:

- "Корень программы" (get_app_root) - папка, где реально лежит exe-файл (или корень проекта при запуске из исходников). Сюда пишутся
  пользовательские, изменяемые данные - база данных, резервные копии, файл резервного пароля. Эти данные должны быть рядом с программой,
  видны и доступны пользователю, и не должны теряться между запусками.

- "Папка ресурсов" (get_resources_dir) - папка, где лежат ТОЛЬКО ДЛЯ ЧТЕНИЯ ресурсы, упакованные вместе с программой при сборке (иконки,
  шрифт). При --onefile PyInstaller распаковывает их во временную папку при каждом запуске (sys._MEIPASS) - для чтения это ничем не
  отличается от обычного файла на диске, но писать туда не нужно (и бессмысленно - при следующем запуске эта временная папка будет уже другой).
"""
import sys
import os


def get_app_root():
    """Папка, где реально лежит исполняемый файл программы - для хранения пользовательских данных (база, резервные копии, файл
    резервного пароля). При запуске из исходников - корень проекта (на два уровня выше этого файла, src/app_paths.py -> src/.. )."""
    if getattr(sys, 'frozen', False):
        return os.path.dirname(sys.executable)
    return os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def get_resources_dir():
    """Папка с ресурсами (иконки, шрифт) - только для чтения. При сборке PyInstaller ресурсы могут оказаться во временной папке распаковки
    (--onefile, sys._MEIPASS) или в папке _internal рядом с exe(--onedir - там sys._MEIPASS указывает именно на эту папку)."""
    if getattr(sys, 'frozen', False):
        base = getattr(sys, '_MEIPASS', os.path.dirname(sys.executable))
        return os.path.join(base, 'resources')
    return os.path.join(get_app_root(), 'src', 'resources')