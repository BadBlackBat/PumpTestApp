# -*- coding: utf-8 -*-
"""
auth.py - проверка пароля для действий, требующих подтверждения
(удаление записи/модификации, добавление насоса и т.п.).

Устроено предельно просто, без какого-либо шифрования - по договорённости,
защита именно "минимальная": лёгкий барьер, а не настоящая система
безопасности.

Два независимых способа входа - подходит любой из них (см. check_password):

1. ОСНОВНОЙ пароль - обычная строковая константа прямо здесь, в коде
   (DEFAULT_PASSWORD). Чтобы сменить пароль для всей команды - поменять
   эту строку и заново собрать/раздать программу.

2. РЕЗЕРВНЫЙ (аварийный) пароль - хранится ЛОКАЛЬНО на конкретном
   компьютере, в скрытом файле рядом с программой (не через
   синхронизацию сети - иначе он был бы доступен всем, а не только
   тому, кто должен его знать). Внутри файла - не сам пароль, а его
   SHA-256 хеш (одностороннее преобразование - из хеша нельзя получить
   обратно исходный пароль, можно только сравнивать "хеш введённого" с
   "хешем сохранённого"). Создаётся/меняется через отдельный скрипт
   generate_password_override.py (не часть самой программы) - там же
   подробно объяснено, как им пользоваться.

   Если резервного файла нет - работает только основной пароль. Если
   есть - работают ОБА варианта одновременно (не заменяет основной, а
   дополняет его) - это осознанный выбор: резервный пароль существует
   именно как аварийный вход на случай, если основной забыт/утерян, а
   не как замена его на конкретном компьютере.
"""
import os
import hashlib

# Основной пароль - меняется прямо здесь, одной строкой
DEFAULT_PASSWORD = "admin"

# Резервный (аварийный) файл - скрытая папка рядом с программой, с
# намеренно непримечательным названием
_OVERRIDE_DIR_NAME = ".pumpapp_sys"
_OVERRIDE_FILE_NAME = "sys.dat"


def _override_path():
    """Путь к резервному файлу - в папке на два уровня выше этого файла
    (src/../ - то есть рядом с самой программой, не внутри src)."""
    base_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    return os.path.join(base_dir, _OVERRIDE_DIR_NAME, _OVERRIDE_FILE_NAME)


def _read_override_hash():
    """Читает хеш резервного пароля из файла, если он существует.
    Возвращает None, если файла нет или его не удалось прочитать -
    в этом случае резервный вход просто не работает, ошибок наружу не
    показываем (это штатная ситуация - на большинстве компьютеров такого
    файла не будет вообще)."""
    path = _override_path()
    if not os.path.exists(path):
        return None
    try:
        with open(path, 'r', encoding='utf-8') as f:
            return f.read().strip()
    except OSError:
        return None


def check_password(entered):
    """Проверяет введённый пароль - подходит любой из двух вариантов
    (см. описание модуля). Пустая строка никогда не считается верной,
    даже если DEFAULT_PASSWORD случайно окажется пустым."""
    if not entered:
        return False
    if entered == DEFAULT_PASSWORD:
        return True
    override_hash = _read_override_hash()
    if override_hash:
        entered_hash = hashlib.sha256(entered.encode('utf-8')).hexdigest()
        if entered_hash == override_hash:
            return True
    return False