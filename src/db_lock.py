# -*- coding: utf-8 -*-
"""
db_lock.py - защита от одновременной записи в общую сетевую базу данных.

Смысл: лок занимается только на сам момент записи (доли секунды - от
"начали писать" до "закоммитили"), а НЕ на всё время, пока пользователь
заполняет диалог - иначе можно было бы держать базу занятой по 5-10
минут, пока кто-то редактирует насос. Пока пользователь просто вводит
данные в форму - к файлу базы никто не обращается вообще, лок в этот
момент не нужен.

В локальном режиме (или если сетевой режим не настроен/не активен) этот
модуль ничего не делает - concurrent-запись там в принципе невозможна,
файл используется только этим одним процессом.
"""
import os
import time
import socket
import getpass
from contextlib import contextmanager
from . import db_settings

# Лок старше этого считается "осиротевшим" (например, программа
# аварийно закрылась прямо во время записи, не успев снять лок за
# собой) - его можно спокойно снять и попробовать снова, а не блокировать
# всех навсегда из-за одного сбоя
LOCK_TIMEOUT_SECONDS = 60
RETRY_COUNT = 6
RETRY_DELAY_SECONDS = 0.4


class DatabaseLockedError(Exception):
    """Не удалось получить эксклюзивный доступ на запись - кто-то ещё
    прямо сейчас сохраняет изменения в общую сетевую базу. Вызывающий
    код должен поймать это исключение и показать пользователю понятное
    сообщение вместо падения программы."""
    pass


def _lock_path():
    # os.path.normpath приводит путь к виду, который однозначно понимает
    # ОС (на Windows - обратные слэши, включая двойной префикс UNC-пути)
    # - без этого сетевой путь с прямыми слэшами (например,
    # //сервер/папка/...) мог интерпретироваться низкоуровневым os.open()
    # иначе, чем более "снисходительными" API вроде os.path.exists() или
    # SQLite - отсюда и был баг: сеть определялась верно, а сам лок-файл
    # создавался/искался не туда
    network_path = os.path.normpath(db_settings.get_network_db_path())
    return network_path + '.lock'


def _try_acquire(lock_path):
    """Пытается эксклюзивно создать лок-файл (O_EXCL - гарантированно не
    даст создать, если файл уже существует у кого-то другого - атомарная
    операция на уровне файловой системы, а не "проверили, потом
    создали", что было бы уязвимо к гонке между двумя процессами)."""
    try:
        fd = os.open(lock_path, os.O_CREAT | os.O_EXCL | os.O_WRONLY)
        try:
            info = f"{socket.gethostname()}:{getpass.getuser()}:{time.time()}"
            os.write(fd, info.encode('utf-8', errors='replace'))
        finally:
            os.close(fd)
        return True
    except FileExistsError:
        # Лок уже есть - проверяем, не "протух" ли он (осиротевший лок
        # от аварийно завершившегося процесса)
        if _is_stale(lock_path):
            try:
                os.remove(lock_path)
            except OSError:
                pass
            return _try_acquire(lock_path)
        return False
    except OSError:
        # Сетевая папка сейчас недоступна и т.п. - не рискуем считать,
        # что лок получен
        return False


def _is_stale(lock_path):
    """Определяет, "протух" ли уже существующий лок-файл (например,
    остался от процесса, который аварийно завершился, не успев снять
    его за собой) - по времени, записанному ВНУТРИ содержимого самого
    файла (см. _try_acquire), а НЕ по метаданным файловой системы (mtime).

    На практике время изменения файла (mtime), которое сообщает сетевая
    папка, может ощутимо отставать от локальных часов клиента (задержка
    в несколько минут - наблюдалось на реальной сетевой шаре) - из-за
    этого свежесозданный лок мог сразу выглядеть "протухшим", и лок
    снимался бы сразу же после создания, даже если он ещё активен.
    Записанное самим же кодом время внутри файла не зависит от того,
    насколько точно и своевременно сетевая папка обновляет метаданные."""
    try:
        with open(lock_path, 'r', encoding='utf-8', errors='replace') as f:
            content = f.read().strip()
        created_at = float(content.split(':')[-1])
        age = time.time() - created_at
        return age > LOCK_TIMEOUT_SECONDS
    except (OSError, ValueError, IndexError):
        # Не удалось прочитать/распознать содержимое (пустой файл,
        # повреждён, или создан не нашим кодом) - считаем протухшим,
        # чтобы не блокировать всех навсегда из-за постороннего файла
        return True


def _release(lock_path):
    try:
        os.remove(lock_path)
    except OSError:
        pass


@contextmanager
def acquire_write_lock():
    """Контекстный менеджер для эксклюзивной записи в общую сетевую базу.

    В локальном режиме (или если сеть не настроена/не активна) - просто
    ничего не делает (yield сразу) - в локальном режиме конкурентная
    запись невозможна в принципе, лок там не нужен и не должен как-либо
    влиять на поведение программы.

    Использование:
        with db_lock.acquire_write_lock():
            ... сама запись в базу (INSERT/UPDATE/DELETE + commit) ...

    Поднимает DatabaseLockedError, если за несколько попыток так и не
    удалось получить эксклюзивный доступ - вызывающий код должен это
    поймать и показать пользователю понятное сообщение."""
    if not db_settings.is_network_mode_active():
        yield
        return

    lock_path = _lock_path()
    acquired = False
    for _ in range(RETRY_COUNT):
        if _try_acquire(lock_path):
            acquired = True
            break
        time.sleep(RETRY_DELAY_SECONDS)

    if not acquired:
        raise DatabaseLockedError(
            "База данных сейчас занята другим пользователем.\n"
            "Попробуйте сохранить ещё раз через несколько секунд."
        )

    try:
        yield
    finally:
        _release(lock_path)