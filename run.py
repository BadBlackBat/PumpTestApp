# -*- coding: utf-8 -*-
"""
run.py - точка входа для сборки PyInstaller.

Лежит В КОРНЕ ПРОЕКТА (рядом с папкой src, НЕ внутри неё) - это важно.
Все модули внутри src/ используют относительные импорты (например,
"from . import database as db", "from .gui import MainWindow") - они
корректно разбираются только тогда, когда src воспринимается как
ПАКЕТ, а не как папка с отдельными скриптами. Если направить PyInstaller
прямо на src/main.py как на точку входа - относительные импорты внутри
него не разрешатся, сборка не соберётся или упадёт при запуске.

Обычный запуск при разработке (python -m src.main, из корня проекта)
работает по этой же причине - "-m src.main" тоже запускает main.py как
часть пакета src, а не как отдельный файл.

Использование: PyInstaller получает именно этот файл как точку входа
(смотри PumpTestApp.spec), а не что-либо внутри src/ напрямую.
"""
from src.main import main

if __name__ == "__main__":
    main()